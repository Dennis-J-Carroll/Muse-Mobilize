import { test, expect, openTool } from './fixtures';

test('discuss unsaved Theme previews only chosen text, preserves drafts through failure and placement', async ({ page, request, projectId }, info) => {
  await page.setViewportSize({ width: 1500, height: 1000 });
  const question = page.getByRole('textbox', { name: 'Ask Muse', exact: true });
  await question.fill('Keep my question about belonging.');
  await openTool(page, 'Themes');
  await page.getByRole('button', { name: 'Add first theme', exact: true }).click();
  const editor = page.locator('.theme-drawer');
  await editor.getByLabel('Theme name', { exact: true }).fill('Belonging');
  await editor.getByLabel('Working meaning', { exact: true }).fill('Unsaved meaning, shared only by choice.');
  let asks: any[] = [];
  page.on('request', req => { if (req.url().endsWith('/ask')) asks.push(req.postDataJSON()); });
  await editor.getByRole('button', { name: 'Discuss this card', exact: true }).click();
  const conversation = page.getByRole('region', { name: 'Muse conversation', exact: true });
  await expect(question).toBeFocused();
  await expect(question).toHaveValue('Keep my question about belonging.');
  const excerpt = page.getByLabel('Card excerpt to share');
  await expect(excerpt).toHaveValue(/Unsaved meaning, shared only by choice/);
  expect(asks).toHaveLength(0);
  expect((await (await request.get(`/api/projects/${projectId}/scenes`)).json()).board.themes).toHaveLength(0);
  await excerpt.fill('Theme: Belonging\nOnly this edited excerpt.');
  await page.route('**/ask', route => route.fulfill({ status: 503, json: { error: 'Temporary test failure' } }), { times: 1 });
  await conversation.getByRole('button', { name: 'Ask', exact: true }).click();
  await expect(page.getByText('Temporary test failure', { exact: true })).toBeVisible();
  await expect(question).toHaveValue('Keep my question about belonging.');
  await expect(excerpt).toHaveValue('Theme: Belonging\nOnly this edited excerpt.');
  await conversation.getByRole('button', { name: 'Tools tab', exact: true }).click();
  await expect(excerpt).toBeVisible();
  await page.getByRole('button', { name: 'Open Muse conversation', exact: true }).click();
  await conversation.getByRole('button', { name: 'Ask', exact: true }).click();
  await expect(conversation.locator('.run-text')).toBeVisible();
  await expect(excerpt).toHaveCount(0);
  expect(asks.at(-1).sharedExcerpt).toBe('Theme: Belonging\nOnly this edited excerpt.');
  expect(asks.at(-1).selection).toBeNull();
  await page.keyboard.press('Escape');
  await expect(editor.getByRole('textbox', { name: 'Working meaning', exact: true })).toHaveValue('Unsaved meaning, shared only by choice.');
  await editor.getByRole('button', { name: 'Discuss this card', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(question).toBeInViewport();
  await expect(conversation.getByRole('button', { name: 'Ask', exact: true })).toBeInViewport();
  await page.screenshot({ path: info.outputPath('discuss-theme-phone.png'), animations: 'disabled' });
});

test('saved character and scene cards exclude linked material; removal and project switching clear attachments', async ({ page, request, projectId }) => {
  const root = `/api/projects/${projectId}`;
  const { entity } = await (await request.post(`${root}/canon/entities`, { data: { type: 'character', name: 'Linked secret character', summary: 'Private linked summary', character: { attributes: { goals: ['Find witness'], fears: ['Forget'] } } } })).json();
  await request.post(`${root}/scenes`, { data: { title: 'Hearing', summary: 'A witness arrives.', purpose: 'Test an oath.', assets: [{ kind: 'character', refId: entity.id, role: 'present' }] } });
  await openTool(page, 'Characters');
  await page.getByRole('button', { name: /Linked secret character/ }).first().click();
  await page.locator('.identity-actions').getByRole('button', { name: 'Discuss this card' }).click();
  const excerpt = page.getByLabel('Card excerpt to share');
  await expect(excerpt).toHaveValue(/Find witness/);
  await page.getByRole('button', { name: 'Remove attachment' }).click();
  await expect(excerpt).toHaveCount(0);
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Open full Cast', exact: true }).click();
  await openTool(page, 'Scenes');
  await page.locator('.scene-lane').getByRole('button', { name: 'Discuss this card' }).click();
  await expect(excerpt).toHaveValue(/Test an oath/);
  await expect(excerpt).not.toHaveValue(/Linked secret character|Private linked summary/);
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Project menu' }).click();
  await page.getByRole('button', { name: 'New Project', exact: true }).click();
  const newStory = page.getByRole('dialog', { name: 'New story' });
  await newStory.getByLabel('Story name (optional)').fill(`Discussion switch ${projectId}`);
  await newStory.getByRole('button', { name: 'Start writing' }).click();
  await expect(page.getByRole('heading', { name: `Discussion switch ${projectId}`, exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Open Muse conversation', exact: true }).click();
  await expect(excerpt).toHaveCount(0);
});

test('Plot Architect opens above expanded plot; Plot discussion stages the selected beat', async ({ page, request, projectId }) => {
  await request.post(`/api/projects/${projectId}/plot/nodes`, { data: { title: 'The oath breaks', summary: 'A witness refuses.', details: { goal: 'Find truth', stakes: 'Reputation' }, position: { x: 180, y: 280 } } });
  await openTool(page, 'Plot Outline');
  const plot = page.locator('.pane-plot');
  await plot.getByText('The oath breaks', { exact: true }).first().click();
  await page.getByRole('button', { name: 'ask Architect', exact: true }).click();
  const architect = page.getByRole('region', { name: 'Architect conversation', exact: true });
  await expect(architect).toBeVisible();
  await expect(plot).toHaveClass(/pane-maximized/);
  await page.keyboard.press('Escape');
  await page.locator('.plot-folio').getByRole('button', { name: 'Discuss this card' }).click();
  await expect(page.getByLabel('Card excerpt to share')).toHaveValue(/Reputation/);
});
